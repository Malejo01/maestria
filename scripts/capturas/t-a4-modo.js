(async () => {
  const esperar = (ms) => new Promise((r) => setTimeout(r, ms))
  const nav = [...document.querySelectorAll('a,button')].find((x) => x.textContent.trim() === 'Mis materias')
  if (nav) nav.click()
  for (let i = 0; i < 80 && ![...document.querySelectorAll('button')].some((b) => /Crear cuestionario/.test(b.textContent)); i++) await esperar(250)
  const crear = [...document.querySelectorAll('button')].find((b) => /Crear cuestionario/.test(b.textContent))
  if (!crear) throw new Error('LISTA sin crear')
  crear.click()
  await esperar(2500)
  const tema = [...document.querySelectorAll('button')].find((b) => /Obst|campo de la matem|valores/i.test(b.textContent) && b.textContent.length < 120)
  if (!tema) throw new Error('LISTA sin tema: ' + [...document.querySelectorAll('button')].map((b) => b.textContent.trim().slice(0, 40)).join(' | ').slice(0, 600))
  tema.click()
  await esperar(500)
  const generar = [...document.querySelectorAll('button')].find((b) => /Generar cuestionario/.test(b.textContent))
  generar.click()
  await esperar(1500)
})()
