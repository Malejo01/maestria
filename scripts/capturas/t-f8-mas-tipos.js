(async () => {
  const esperar = (ms) => new Promise((r) => setTimeout(r, ms))
  const boton = (re) => [...document.querySelectorAll('button')].find((b) => re.test((b.getAttribute('aria-label') || b.textContent).trim()))
  for (let i = 0; i < 60 && !boton(/^Crear cuestionario/); i++) await esperar(250)
  boton(/^Crear cuestionario/).click()
  for (let i = 0; i < 60 && !boton(/Unidad 1/); i++) await esperar(250)
  boton(/Unidad 1/).click()
  await esperar(400)
  boton(/^Generar cuestionario/).click()
  for (let i = 0; i < 40 && !boton(/Más tipos/); i++) await esperar(250)
  boton(/Más tipos/).click()
  await esperar(400)
  boton(/Emparejamiento/).click()
  await esperar(150)
  boton(/Ordenamiento/).click()
  await esperar(300)
  boton(/Más tipos/).scrollIntoView({ block: 'start' })
  await esperar(300)
})()
