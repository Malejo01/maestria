(async () => {
  const esperar = (ms) => new Promise((r) => setTimeout(r, ms))
  const nav = [...document.querySelectorAll('a,button')].find((x) => x.textContent.trim() === 'Mis materias')
  if (nav) nav.click()
  for (let i = 0; i < 80 && ![...document.querySelectorAll('p')].some((p) => /^E2E · Geografía 22\/11 19:06/.test(p.textContent)); i++) await esperar(250)
  const p = [...document.querySelectorAll('p')].find((x) => /^E2E · Geografía 22\/11 19:06/.test(x.textContent))
  if (!p) throw new Error('LISTA sin materia')
  ;(p.closest('[data-slot="card"]') || p.parentElement.parentElement).dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))
  await esperar(1500)
  const boton = [...document.querySelectorAll('button')].find((b) => (b.getAttribute('aria-label') || '').startsWith('Separar en temas: Fenómenos naturales'))
  if (!boton) throw new Error('LISTA sin botón: ' + [...document.querySelectorAll('button')].map((b) => b.getAttribute('aria-label')).filter(Boolean).join(' | ').slice(0, 300))
  boton.click()
  for (let i = 0; i < 40 && !document.querySelector('[data-separar-tema]'); i++) await esperar(250)
  document.querySelector('[data-separar-tema]').scrollIntoView({ block: 'center' })
  await esperar(500)
})()
